import { chromium } from "@playwright/test";
import { readFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
const ROOT = process.cwd();
const OUT = resolve(ROOT, "design/audit/before");
const env = Object.fromEntries(readFileSync(resolve(ROOT, ".env"),"utf8").split(/\r?\n/).filter(l=>l.includes("=")&&!l.trim().startsWith("#")).map(l=>{const i=l.indexOf("=");let v=l.slice(i+1).trim();if((v.startsWith('"')&&v.endsWith('"'))||(v.startsWith("'")&&v.endsWith("'")))v=v.slice(1,-1);return [l.slice(0,i).trim(),v]}));
mkdirSync(OUT,{recursive:true});
const b = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ baseURL: "http://localhost:3000", viewport:{width:1920,height:1080} });
const login = await ctx.request.post("/api/auth/login",{data:{username:env.APP_USERNAME,password:env.APP_PASSWORD,next:"/"}});
console.log("login", login.status());
const p = await ctx.newPage();
p.on("console", m => { if (m.type()==="error") console.log("CONSOLE", m.text().slice(0,140)); });
p.on("response", r => { const u=r.url(); if(u.includes("/api/")) console.log(r.status(), u.replace("http://localhost:3000","")); });
await p.goto("/", {waitUntil:"domcontentloaded"});
await p.waitForTimeout(12000);
const stats = await p.evaluate(() => Array.from(document.querySelectorAll("video")).map(v => ({w:v.videoWidth,h:v.videoHeight,rs:v.readyState,paused:v.paused})));
console.log("videos", JSON.stringify(stats));
await p.screenshot({path: resolve(OUT,"dashboard-desktop-loaded.png")});
await p.screenshot({path: resolve(OUT,"dashboard-desktop-loaded-full.png"), fullPage:true});
await b.close();
